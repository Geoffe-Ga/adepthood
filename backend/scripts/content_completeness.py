"""Gate the served Course for completeness and generate its two inventories.

Issue #3070. ``sync_content --check`` proves ``backend/content/`` is the pinned
upstream commit byte-for-byte, and ``build_stage_correspondence --check`` proves
the stage correspondence is generated from it. Neither proves the Course a
reader is served is *complete*: a heading-only chapter or a skipped chapter
number passes both. This script closes that gap:

    python -m scripts.content_completeness           # regenerate the inventories, then gate
    python -m scripts.content_completeness --check   # CI: gate and diff, write nothing

The served Course is exactly the manifest's chapters, stage intros and site
resources; vendored files the manifest does not name (``backup/``, the export
tables of contents) are out of scope. Every stage intro shares its file with
chapter 1 upstream, so each file is graded once and carries every ref that
serves it.

Checks (each in :data:`CHECKS`, each proven to fire by a violating fixture in
``tests/scripts/test_content_completeness.py``):

* ``stage_coverage`` -- each stage 1..``STAGE_COUNT`` has exactly one intro and
  at least one chapter, and nothing lies outside that range.
* ``duplicate_ref`` -- chapter ids, per-stage chapter slugs, intro ids and
  resource slugs are unique.
* ``thin_chapter`` -- a chapter body has at least ``MIN_CHAPTER_WORDS`` words.
* ``numbering_gap`` -- per stage, chapter numbers run 1..n with no gap and no
  repeat.
* ``broken_relative_link`` -- a relative link or image resolves to a file
  inside the content dir, and a ``.md#fragment`` names a heading there.
* ``broken_anchor`` -- an in-file ``#anchor`` names a heading of that file.
* ``insecure_external_link`` / ``redirect_wrapper_link`` -- external links are
  https and are not Google Docs ``google.com/url`` redirect wrappers.

Only ``thin_chapter`` and ``numbering_gap`` are content the owner must write
upstream, so only they may be recorded in ``src/curriculum/content_gaps.json``
(each pending owner review). A recorded gap that no longer reproduces fails as
stale, so fixing the content upstream forces the record to shrink. Link
failures are never waivable.

Inventories (regenerated by default mode, byte-compared by ``--check``):

* ``src/curriculum/source_references.json`` -- every external link in served
  content, by file and the refs serving it. A draft input to the owner's
  bibliography, explicitly **not** a bibliography and carrying no rights status.
* ``src/curriculum/practice_recommendations.json`` -- every chapter whose title
  names a practice or protocol, each ``unreviewed``. Mapping decisions belong in
  a separate owner-reviewed sidecar, since regeneration overwrites this file.

Like its siblings this script imports nothing from ``src/``: the CI job
installs only ``httpx`` and ``jsonschema``. ``tests/test_content_completeness_parity.py``
pins its frontmatter stripper and stage count to the server's.

Exit codes: 0 when the Course is complete (or every gap is recorded) and the
inventories are current; 1 otherwise, with every problem on stderr.
"""

